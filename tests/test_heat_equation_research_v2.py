# Class 2 — Real-CSV viability with corrected BC
# ---------------------------------------------------------------------------


class TestRealCSVViabilityV2:
    """Re-run the M7 viability sweep with the corrected BC.

    Parametrised over the same 7 real fixtures as M7. For each, derive
    ``x_surface_continuous`` from the M2a classifier's
    ``surface_assignment.position_normalised`` (the M6 inferred position),
    then call :func:`fit_heat_equation_inverse_v2`.
    """

    _RESULTS: dict[str, dict] = {}

    @pytest.mark.parametrize(
        "spec",
        REAL_FIXTURES,
        ids=lambda s: s["label"],
    )
    def test_v2_inversion_runs_on_real_csv(self, spec):
        df = _segmented_real_fixture(spec)
        x_surf_cont = _classifier_x_surface_for_spec(spec)
        result = fit_heat_equation_inverse_v2(
            df=df,
            in_dough_sensors=spec["in_dough"],
            x_surface_continuous=x_surf_cont,
            x_core_init=-0.05,
            alpha_init=1e-3,
            downsample_factor=4,
        )
        TestRealCSVViabilityV2._RESULTS[spec["label"]] = {
            **result,
            "fixture_name": spec["fixture_name"],
            "expected_curve_idx": spec["expected_curve_idx"],
            "n_in_dough": len(spec["in_dough"]),
            "x_surface_continuous": x_surf_cont,
            "in_dough": list(spec["in_dough"]),
        }
        # Hard contract: optimiser must run.
        assert result["converged"] or result["n_iter"] >= 50, (
            f"{spec['label']}: optimiser failed to make progress"
            f" (iter={result['n_iter']})"
        )


