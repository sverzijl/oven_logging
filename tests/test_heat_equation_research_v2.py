_M6_SURFACE_POSITION_CACHE: dict[tuple, float] = {}


def _classifier_x_surface_for_spec(spec: dict) -> float:
    """Return the M2a-inferred continuous x_dough_air for a fixture spec.

    Cached per (fixture_name, expected_curve_idx) to avoid re-running the
    classifier on every test.
    """
    key = (spec["fixture_name"], spec["expected_curve_idx"])
    if key in _M6_SURFACE_POSITION_CACHE:
        return _M6_SURFACE_POSITION_CACHE[key]
    df = _segmented_real_fixture(spec)
    geom = lookup_geometry(probe_sn=None, probe_model=None)
    a = classify(df, sample_period_ms=5000, probe_geometry=geom)
    if a.surface_assignment is None:
        # Full-immersion: no interface. Fall back to the v1 spec's discrete
        # x_surface so the test still has something to invert.
        x = float(spec["x_surface"])
    else:
        x = float(a.surface_assignment.position_normalised)
    _M6_SURFACE_POSITION_CACHE[key] = x
    return x


# ---------------------------------------------------------------------------
# Class 1 — Sanity check: v2 on a synthetic whose true BC IS the interp.
# ---------------------------------------------------------------------------


class TestV2SanityOnSynthetic:
    """v2 should reproduce v1's synthetic-recovery numbers when the
    interface lies on a sensor (so the 'interpolated' BC reduces to the
    sensor's own time series and the two methods agree).
    """

    def test_recovers_known_x_core_no_noise_v2(self):
        x_core_true = -0.15
        alpha_true = 1.5e-3
        df, surf = _synthetic_dough_observations(
            alpha_true=alpha_true,
            x_core_true=x_core_true,
            x_surface=5 / 7,  # T6 position
            in_dough_sensors=("T1", "T2", "T3", "T4", "T5"),
            noise_sigma_c=0.0,
            seed=1,
        )
        # Overwrite T6 with the surface BC so the interpolation at x = 5/7
        # reduces exactly to surf — establishes that v2 wiring is sane on a
        # case where its BC equals the v1 BC.
        df["T6"] = surf
        df["T7"] = surf
        df["T8"] = surf
        result = fit_heat_equation_inverse_v2(
            df=df,
            in_dough_sensors=["T1", "T2", "T3", "T4", "T5"],
            x_surface_continuous=5 / 7,
            x_core_init=-0.05,
            alpha_init=1e-3,
            downsample_factor=4,
        )
        assert result["converged"], f"v2 did not converge: {result}"
        assert result["bc_source"] == "interpolated_v2"
        # Same recovery quality as v1's synthetic test.
        assert abs(result["x_core"] - x_core_true) < 0.02, (
            f"x_core_fit = {result['x_core']:.4f}; expected ≈ {x_core_true}"
        )
        assert abs(result["alpha"] - alpha_true) / alpha_true < 0.5, (
            f"alpha_fit = {result['alpha']:.2e}; expected ≈ {alpha_true:.2e}"
        )


