# The 3 representative fixtures for the profile-likelihood scan: a
# motivating BA3C, a different probe (100098DE picks T7 as surface), and a
# lidded case that was pathological in M7.
PROFILE_LIKELIHOOD_LABELS = ("BA3C_0946", "100098DE_1351", "wonder_white")
PROFILE_LIKELIHOOD_FIXTURES = [
    s for s in REAL_FIXTURES if s["label"] in PROFILE_LIKELIHOOD_LABELS
]


class TestProfileLikelihood:
    """Profile-likelihood scan on 3 representative fixtures.

    Grid: x_core ∈ [-0.5, +0.5] in 25 steps. For each fixture, refit α
    only and record the (x_core, alpha_best, loss) curve.

    Verdict criterion (computed at report time, not asserted here):

    * Loss-flat fraction = (max(loss) - min(loss)) / median(loss) over the
      grid. If it is < 0.05, the loss is genuinely flat (structural
      degeneracy). If it is large with a clear minimum interior to the
      grid, the M7 joint optimiser converged early.
    """

    _RESULTS: dict[str, pd.DataFrame] = {}

    @pytest.mark.parametrize(
        "spec",
        PROFILE_LIKELIHOOD_FIXTURES,
        ids=lambda s: s["label"],
    )
    def test_profile_likelihood_scan(self, spec):
        df = _segmented_real_fixture(spec)
        x_surf_cont = _classifier_x_surface_for_spec(spec)
        # Grid stays interior to x_surface_continuous (the model rejects
        # x_core ≥ x_surface). Truncate to safe range.
        upper = min(0.5, x_surf_cont - 0.05)
        x_grid = np.linspace(-0.5, upper, 25)
        scan = profile_likelihood_x_core(
            df=df,
            in_dough_sensors=spec["in_dough"],
            x_surface_continuous=x_surf_cont,
            x_core_grid=x_grid,
            alpha_init=1e-3,
            downsample_factor=4,
        )
        TestProfileLikelihood._RESULTS[spec["label"]] = scan
        # Soft contract: at least 80% of grid points must yield a finite loss.
        finite_count = int(np.isfinite(scan["loss"]).sum())
        assert finite_count >= int(0.8 * len(x_grid)), (
            f"{spec['label']}: only {finite_count}/{len(x_grid)} grid "
            f"points produced a finite loss"
        )


# ---------------------------------------------------------------------------
# Class 4 — synthetic_shallow_insertion misfit baseline
# ---------------------------------------------------------------------------


class TestSyntheticShallowInsertionMisfit:
    """True model-misfit baseline.

    ``synthetic_shallow_insertion`` was generated by the role-classifier
    fixture-builder, NOT by the heat-eq forward solver. Inverting it tests
    whether the heat equation is the right *model class* for this
    geometry, not just for self-consistent synthetic data.
    """

    _RESULTS: dict = {}

    def test_synthetic_shallow_insertion_misfit(self):
        case = next(
            c for c in CASES if c["name"] == "synthetic_shallow_insertion"
        )
        df = case["df"].copy()
        # Restrict to the bake window (matches the fixture annotations).
        starts = case.get("expected_starts") or [0]
        ends = case.get("expected_ends") or [len(df) - 1]
        s, e = int(starts[0]), int(ends[0])
        sub = df.iloc[s : e + 1].reset_index(drop=True)
        if "Timestamp" in sub.columns:
            t0 = float(sub["Timestamp"].iloc[0])
            sub["Timestamp"] = sub["Timestamp"].to_numpy(dtype=float) - t0
        # Fixture's ground-truth interface is at 2.5/7 ≈ 0.357.
        x_surf_cont = float(case["expected_x_dough_air_normalised"])
        # In-dough = T1, T2 (the fixture's ground-truth dough sensors).
        in_dough = ["T1", "T2"]
        result = fit_heat_equation_inverse_v2(
            df=sub,
            in_dough_sensors=in_dough,
            x_surface_continuous=x_surf_cont,
            x_core_init=-0.05,
            alpha_init=1e-3,
            downsample_factor=2,
        )

        # Per-sensor RMSE breakdown (informative — not asserted hard).
        from src.data.spatial_reconstruction.heat_equation import (
            _build_observation_matrix,
            solve_heat_eq_forward as fwd,
        )
        from src.data.spatial_reconstruction.profile import (
            interpolate_temperature_series_at,
        )

        t_obs, T_obs, x_obs = _build_observation_matrix(
            df=sub,
            in_dough_sensors=in_dough,
            sensor_names=SENSOR_NAMES,
            sensor_positions_normalised=SENSOR_POSITIONS,
            downsample_factor=2,
        )
        surf_full = interpolate_temperature_series_at(
            sub,
            positions=SENSOR_POSITIONS,
            x_target=x_surf_cont,
            sensors=SENSOR_NAMES,
        ).to_numpy(dtype=float)
        t_full = sub["Timestamp"].to_numpy(dtype=float)
        T_surf_obs = np.interp(t_obs, t_full, surf_full)
        T_pred = fwd(
            alpha=result["alpha"],
            x_core=result["x_core"],
            x_surface=x_surf_cont,
            t_grid=t_obs,
            T_surface_series=T_surf_obs,
            T_initial=result["T_initial"],
            n_spatial=30,
            sample_x=x_obs,
        )
        per_sensor_rmse = {
            in_dough[k]: float(np.sqrt(np.mean((T_pred[:, k] - T_obs[:, k]) ** 2)))
            for k in range(len(in_dough))
        }

        TestSyntheticShallowInsertionMisfit._RESULTS = {
            **result,
            "per_sensor_rmse": per_sensor_rmse,
            "x_surface_continuous": x_surf_cont,
            "in_dough": list(in_dough),
        }
        # Hard contract: classifier converges. The question is whether the
        # residuals are small, not whether the optimiser ran.
        assert result["converged"] or result["n_iter"] >= 30, (
            f"shallow insertion: optimiser failed (iter={result['n_iter']})"
        )
